ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'qml/assets/authored/world/world-places.json'
ASSETS=ROOT/'qml/assets/authored/world/places'
KINDS=('cottage','market','tower','gate','forge','mine','observatory','statue','lantern','fence','crate','windmill')
STONE=(.51,.56,.54,1);WOOD=(.35,.19,.10,1);ROOF=(.72,.29,.12,1)
GOLD=(.91,.65,.19,1);TEAL=(.12,.48,.47,1);DARK=(.13,.17,.18,1)


@lru_cache(maxsize=1)
def catalog():
    if not SOURCE.is_file():
        return {'schema':'gg.world-places.v1','planet_id':'','map_revision':0,
                'revision':0,'coordinates':'metres','places':[],'residents':[],
                'objects':[],'roads':[]}
    document=json.loads(SOURCE.read_text(encoding='utf-8'))
    if document['schema']!='gg.world-places.v1':raise ValueError('invalid world places')
    return document


class Mesh:
    def __init__(self):self.vertices=bytearray();self.indices=[]
    def triangle(self,a,b,c,color):
        u=[b[i]-a[i] for i in range(3)];v=[c[i]-a[i] for i in range(3)]
        n=(u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0])
        length=math.sqrt(sum(t*t for t in n)) or 1
        base=len(self.vertices)//40
        colors=color if len(color)==3 and isinstance(color[0],tuple) else (color,)*3
        for p,col in zip((a,b,c),colors):self.vertices.extend(struct.pack('<10f',*p,*(t/length for t in n),*col))
        self.indices.extend((base,base+1,base+2))
    def box(self,center,size,color):
        from backend.game_engine_settlement import _box
        _box(self.vertices,self.indices,center,tuple(v/2 for v in size),0,color)
    def beam(self,a,b,width,color):
        dx,dy,dz=(b[i]-a[i] for i in range(3));length=math.sqrt(dx*dx+dy*dy+dz*dz)
        if not length:return
        side=(dz/length*width/2,0,-dx/length*width/2)
        if not side[0] and not side[2]:side=(width/2,0,0)
        up=(-dy*side[2]/length,width/2,dy*side[0]/length)
        ends=[[tuple(p[i]+sx*side[i]+sy*up[i] for i in range(3)) for sx,sy in ((-1,-1),(1,-1),(1,1),(-1,1))] for p in (a,b)]
        for i in range(4):
            j=(i+1)%4
            self.triangle(ends[0][i],ends[0][j],ends[1][j],color)
            self.triangle(ends[0][i],ends[1][j],ends[1][i],color)
        for e in ends:self.triangle(e[0],e[2],e[1],color);self.triangle(e[0],e[3],e[2],color)
    def pyramid(self,center,rx,rz,height,color):
        x,y,z=center;p=[(x-rx,y,z-rz),(x+rx,y,z-rz),(x+rx,y,z+rz),(x-rx,y,z+rz)]
        for i in range(4):self.triangle(p[(i+1)%4],p[i],(x,y+height,z),color)
        self.triangle(p[0],p[1],p[2],color);self.triangle(p[0],p[2],p[3],color)
    def gable(self,x,y,z,width,depth,height,color):
        a=(x-width/2,y,z-depth/2);b=(x+width/2,y,z-depth/2);c=(x,y+height,z-depth/2)
        d=(x-width/2,y,z+depth/2);e=(x+width/2,y,z+depth/2);f=(x,y+height,z+depth/2)
        for p in ((a,b,c),(e,d,f),(a,c,f),(a,f,d),(c,b,e),(c,e,f),(a,d,e),(a,e,b)):self.triangle(*p,color)


def kit_mesh(kind,lod=0,variant=0):
    """Original chunky silhouettes; distant levels retain their real outline."""
    if kind not in KINDS:raise ValueError('unknown architectural kit')
    m=Mesh();detail=lod==0;mid=lod<2
    if kind=='cottage':
        from backend.game_engine_world_style import cottage
        cottage(m,lod)
    elif kind=='market':
        m.gable(0,3.4,0,9,6,1.8,GOLD)
