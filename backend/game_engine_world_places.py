def exclusion_index():
    """Build-only spatial index: woods leave saved towns and roads open."""
    index={}
    circles=[(p['x'],p['z'],p['clearing_m']) for p in catalog()['places']]
    # Roads can displace a house beyond the original village green. Its
    # footprint still belongs to the saved clearing, including roof overhang.
    circles.extend((o['x'],o['z'],14*o['scale']) for o in catalog()['objects'] if o['kind'] in
                   ('cottage','tower','gate','mine','forge','observatory','statue','windmill'))
    for x,z,r in circles:
        for cx in range(math.floor((x-r)/256),math.floor((x+r)/256)+1):
            for cz in range(math.floor((z-r)/256),math.floor((z+r)/256)+1):index.setdefault((cx,cz),[]).append((x,z,r))
    for road in catalog()['roads']:
        for a,b in zip(road['points'],road['points'][1:]):
            n=max(1,math.ceil(math.dist(a,b)/12))
            for i in range(n+1):
                x,z=(a[k]+(b[k]-a[k])*i/n for k in range(2));r=road['width_m']/2+10
                for cx in range(math.floor((x-r)/256),math.floor((x+r)/256)+1):
                    for cz in range(math.floor((z-r)/256),math.floor((z+r)/256)+1):index.setdefault((cx,cz),[]).append((x,z,r))
    return index


@lru_cache(maxsize=1)
def building_index():
    """Saved nearby wall/floor queries, separate from the static GPU batches."""
    result={}
    from backend import game_engine_landscape as landscape
    houses=list(catalog()['objects'])
    if landscape.enabled():
        for row in landscape.catalog()['structures']:
            if row['kind']=='cottage':houses.append(row)
            elif row['kind'] in ('citadel','port-hall','grove-hall','caravan-hall'):
                houses.append(dict(row,kind='cottage',scale=row['scale']*2.5))
    for row in houses:
        if row['kind']!='cottage':continue
        r=10*row['scale']
        for x in range(math.floor((row['x']-r)/64),math.floor((row['x']+r)/64)+1):
            for z in range(math.floor((row['z']-r)/64),math.floor((row['z']+r)/64)+1):result.setdefault((x,z),[]).append(row)
    return result


def building_local(row,x,z):
    angle=math.radians(row['yaw']);c,s=math.cos(angle),math.sin(angle);scale=row['scale']
    dx,dz=x-row['x'],z-row['z']
    return (dx*c-dz*s)/scale,(dx*s+dz*c)/scale,c,s


def building_floor(x,z,body_y,height_at):
    for row in building_index().get((math.floor(x/64),math.floor(z/64)),()):
        lx,lz,_,_=building_local(row,x,z)
        if abs(lx)>4.2 or abs(lz)>3.2:continue
        base=height_at(row['x'],row['z']);scale=row['scale']
        from backend.game_engine_world_style import cottage_roof_y
        roof=base+cottage_roof_y(lx,lz)*scale+.65
        return roof if body_y>=roof-.12 else base+.3*scale+.65
    return None


def building_walls(x,z,body_y,height_at):
    for row in building_index().get((math.floor(x/64),math.floor(z/64)),()):
        lx,lz,c,s=building_local(row,x,z);scale=row['scale'];base=height_at(row['x'],row['z'])
        if body_y>=base+5*scale+.6 or body_y<base-.5:continue
        if abs(lx)>5 or abs(lz)>4:continue
        for cx,cz,hx,hz in ((-4.35,0,.15,3.5),(4.35,0,.15,3.5),(0,3.35,4.5,.15),(-2.8,-3.35,1.65,.15),(2.8,-3.35,1.65,.15)):
            dx,dz=lx-cx,lz-cz;ox,oz=hx+.32/scale-abs(dx),hz+.32/scale-abs(dz)
            if ox<=0 or oz<=0:continue
            if ox<oz:lx+=math.copysign(ox,dx or 1)
            else:lz+=math.copysign(oz,dz or 1)
        x=row['x']+(lx*c+lz*s)*scale;z=row['z']+(-lx*s+lz*c)*scale
    return x,z


def road_mesh(rows,lod=0):
    """Ground-following road page, using world metres and planet curvature."""
    from backend.game_engine_terrain import height_at
    from backend.game_engine_world import DEFAULT_PLANET_RADIUS_METERS
    from backend.game_engine_world_style import road_color
    m=Mesh();radius=DEFAULT_PLANET_RADIUS_METERS
    for road in rows:
        for a,b in zip(road['points'],road['points'][1:]):
            dx,dz=b[0]-a[0],b[1]-a[1];length=math.hypot(dx,dz)
            if not length:continue
            count=max(1,math.ceil(length/(12 if lod==0 else 24 if lod==1 else 48)))
            side=(dz/length*road['width_m']/2,-dx/length*road['width_m']/2)
            for i in range(count):
                # Three vertex-colour bands soften the shoulder without an
                # alpha decal, another material or changing the lane centre.
                local=math.hypot((a[0]+b[0])/2+7398,(a[1]+b[1])/2-248)<480
                bands=(-1,-.72,.72,1) if local else (-1,1)
                for lo,hi in zip(bands,bands[1:]):
                    points=[];colors=[]
                    for t,sign in ((i/count,lo),((i+1)/count,lo),((i+1)/count,hi),(i/count,hi)):
                        x,z=a[0]+dx*t+sign*side[0],a[1]+dz*t+sign*side[1]
                        h=height_at(x,z)+.13;y=math.sqrt(max(1,(radius+h)**2-x*x-z*z))-radius
                        points.append((x,y,z));colors.append(road_color(x,z,abs(sign)) if local else (.48,.34,.20,1))
                    m.triangle(points[0],points[1],points[2],tuple(colors[k] for k in (0,1,2)))
                    m.triangle(points[0],points[2],points[3],tuple(colors[k] for k in (0,2,3)))
    return m.vertices,m.indices
