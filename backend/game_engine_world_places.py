        for x,y in ((-3,9),(3,6.5)):m.box((x,y/2,1.5),(2,y,2),STONE)
        if mid:
            m.box((0,1.5,-3.55),(4,3,.2),ROOF);m.box((0,1.2,-5),(3,2.4,2),DARK)
        if detail:
            m.box((0,2.5,-3.8),(2,1,.3),GOLD)
